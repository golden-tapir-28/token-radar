// Token Radar's model, version radar-2: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every other
// pre-token protocol the watchlist's own rule would keep: no token on record, and not a wrapped, staked
// or bridged product, not an exchange, and not a versioned pool. That is the whole pre-token universe
// the snapshot can see. Live-token protocols are kept apart and shown as the market's own values, never
// mixed into the ranked board.
//
// Implied value is a comparable-companies estimate, built only from the snapshot's own figures:
//
//   category multiple = the median market-cap / TVL of the live-token protocols in the same category
//                         (at least three of them; otherwise the whole market's median), clamped to
//                         [0.05, 1.00]. It is what the market already pays for one dollar of TVL in
//                         this kind of protocol, so a category the market prices richly lifts its
//                         pre-token members and a category it prices thinly lowers them.
//   base              = tvl_usd x category multiple
//   growth            = clamp(change_7d, -50, 150) per cent
//   growth multiplier = 1 + (growth / 100) x 0.6
//   maturity          = 0.55 + min(age_days, 1460) / 1460 x 0.45   (age_days unknown: 365)
//   implied           = max(1, round(base x growth multiplier x maturity))
//
// No protocol name is ever special-cased: the same function scores every row, and the category
// multiples are computed from the snapshot itself at run time, so the model follows the data rather
// than a hand-written list.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
